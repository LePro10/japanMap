export function inUrbanEnvelope(x, z) {
  return x >= -80 && x <= 1490 && z >= -1000 && z <= 960 &&
    !(x >= 620 && x <= 1040 && z <= -520) &&
    !(x >= 560 && x <= 1040 && z >= 780) &&
    Math.hypot(x - 550, z - 510) >= 180;
}
